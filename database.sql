CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(160) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, role ENUM('customer','admin','staff') NOT NULL DEFAULT 'customer',
 is_active TINYINT(1) NOT NULL DEFAULT 1, created_at DATETIME NOT NULL, updated_at DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS categories (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, parent_id BIGINT UNSIGNED NULL, name VARCHAR(160) NOT NULL,
 slug VARCHAR(190) NOT NULL UNIQUE, description TEXT NULL, created_at DATETIME NOT NULL,
 FOREIGN KEY(parent_id) REFERENCES categories(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS products (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, category_id BIGINT UNSIGNED NULL, name VARCHAR(220) NOT NULL,
 slug VARCHAR(240) NOT NULL, sku VARCHAR(100) NULL UNIQUE, barcode VARCHAR(100) NULL, description MEDIUMTEXT NULL,
 price DECIMAL(12,2) NOT NULL DEFAULT 0, sale_price DECIMAL(12,2) NULL, wholesale_price DECIMAL(12,2) NULL,
 stock INT NOT NULL DEFAULT 0, low_stock_at INT NOT NULL DEFAULT 5, image VARCHAR(500) NULL,
 status ENUM('draft','published','archived') NOT NULL DEFAULT 'draft', featured TINYINT(1) NOT NULL DEFAULT 0,
 sold_count INT NOT NULL DEFAULT 0, weight DECIMAL(10,3) NULL, created_at DATETIME NOT NULL, updated_at DATETIME NULL,
 INDEX(status,featured), INDEX(name), INDEX(category_id),
 FOREIGN KEY(category_id) REFERENCES categories(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS product_images (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, product_id BIGINT UNSIGNED NOT NULL, image_path VARCHAR(500) NOT NULL,
 alt_text VARCHAR(255) NULL, sort_order INT NOT NULL DEFAULT 0, FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS product_variations (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, product_id BIGINT UNSIGNED NOT NULL, sku VARCHAR(100) NULL,
 attributes JSON NULL, price DECIMAL(12,2) NOT NULL, stock INT NOT NULL DEFAULT 0,
 FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS addresses (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL, recipient VARCHAR(160) NOT NULL,
 phone VARCHAR(40) NOT NULL, address TEXT NOT NULL, city VARCHAR(120) NOT NULL, is_default TINYINT(1) NOT NULL DEFAULT 0,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS orders (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_number VARCHAR(40) NOT NULL UNIQUE, user_id BIGINT UNSIGNED NOT NULL,
 customer_name VARCHAR(160) NOT NULL, phone VARCHAR(40) NOT NULL, address TEXT NOT NULL, city VARCHAR(120) NOT NULL,
 subtotal DECIMAL(12,2) NOT NULL, shipping_fee DECIMAL(12,2) NOT NULL DEFAULT 0, total DECIMAL(12,2) NOT NULL,
 payment_method VARCHAR(40) NOT NULL, payment_status ENUM('pending','paid','failed','refunded') NOT NULL DEFAULT 'pending',
 order_status ENUM('pending','processing','shipped','delivered','cancelled','returned') NOT NULL DEFAULT 'pending',
 tracking_number VARCHAR(120) NULL, created_at DATETIME NOT NULL, updated_at DATETIME NULL,
 FOREIGN KEY(user_id) REFERENCES users(id), INDEX(user_id,created_at), INDEX(order_status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS order_items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id BIGINT UNSIGNED NOT NULL, product_id BIGINT UNSIGNED NULL,
 product_name VARCHAR(220) NOT NULL, unit_price DECIMAL(12,2) NOT NULL, quantity INT NOT NULL, line_total DECIMAL(12,2) NOT NULL,
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE, FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS payments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id BIGINT UNSIGNED NOT NULL, method VARCHAR(40) NOT NULL,
 amount DECIMAL(12,2) NOT NULL, status VARCHAR(30) NOT NULL DEFAULT 'pending', transaction_reference VARCHAR(190) NULL,
 verified_by BIGINT UNSIGNED NULL, created_at DATETIME NOT NULL, FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS coupons (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, code VARCHAR(80) NOT NULL UNIQUE, discount_type ENUM('fixed','percent') NOT NULL,
 discount_value DECIMAL(10,2) NOT NULL, min_order DECIMAL(12,2) NOT NULL DEFAULT 0, usage_limit INT NULL,
 used_count INT NOT NULL DEFAULT 0, starts_at DATETIME NULL, expires_at DATETIME NULL, is_active TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS reviews (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, product_id BIGINT UNSIGNED NOT NULL, user_id BIGINT UNSIGNED NOT NULL,
 rating TINYINT NOT NULL, review_text TEXT NULL, status ENUM('pending','approved','rejected') NOT NULL DEFAULT 'pending',
 created_at DATETIME NOT NULL, FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE CASCADE,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS pages (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, title VARCHAR(220) NOT NULL, slug VARCHAR(220) NOT NULL UNIQUE,
 content MEDIUMTEXT NULL, meta_title VARCHAR(220) NULL, meta_description VARCHAR(320) NULL,
 is_published TINYINT(1) NOT NULL DEFAULT 0, updated_at DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS blog_posts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, title VARCHAR(220) NOT NULL, slug VARCHAR(220) NOT NULL UNIQUE,
 content MEDIUMTEXT NOT NULL, status ENUM('draft','published') NOT NULL DEFAULT 'draft', published_at DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS banners (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, title VARCHAR(220) NOT NULL, image VARCHAR(500) NULL,
 target_url VARCHAR(500) NULL, is_active TINYINT(1) NOT NULL DEFAULT 1, sort_order INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS settings (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, setting_key VARCHAR(120) NOT NULL UNIQUE, setting_value MEDIUMTEXT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS shipping_methods (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL, base_fee DECIMAL(10,2) NOT NULL DEFAULT 0,
 free_over DECIMAL(12,2) NULL, enabled TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS refunds (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id BIGINT UNSIGNED NOT NULL, amount DECIMAL(12,2) NOT NULL,
 reason TEXT NULL, status ENUM('requested','approved','rejected','processed') NOT NULL DEFAULT 'requested',
 created_at DATETIME NOT NULL, FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS notifications (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NULL, channel VARCHAR(30) NOT NULL,
 recipient VARCHAR(190) NOT NULL, message TEXT NOT NULL, status VARCHAR(30) NOT NULL DEFAULT 'queued', created_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS activity_logs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NULL, action VARCHAR(120) NOT NULL,
 details TEXT NULL, ip_address VARCHAR(45) NULL, created_at DATETIME NOT NULL,
 INDEX(created_at), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
